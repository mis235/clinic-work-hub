const dayIndex = (date) => Math.floor(new Date(date + "T00:00:00Z").getTime() / 86400000);
export const greetingFor = (hhmm) => { const h = Number(hhmm.slice(0, 2)); return h < 12 ? "Good Morning" : h < 17 ? "Good Afternoon" : "Good Evening"; };
/** The line for a date and time of day. Morning and afternoon use the morning list, evening uses the evening list. */
export const quoteFor = (date, hhmm) => { const list = Number(hhmm.slice(0, 2)) >= 17 ? EVENING : MORNING; return list[dayIndex(date) % list.length]; };
